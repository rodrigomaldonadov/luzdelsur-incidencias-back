CREATE TABLE incident (
    id                  UUID PRIMARY KEY,
    sector              VARCHAR(120) NOT NULL,
    sector_key          VARCHAR(120) NOT NULL,
    failure_type        VARCHAR(40)  NOT NULL,
    status              VARCHAR(24)  NOT NULL,
    certainty           VARCHAR(16)  NOT NULL,
    requires_review     BOOLEAN      NOT NULL DEFAULT FALSE,
    priority_score      DOUBLE PRECISION NOT NULL DEFAULT 0,
    priority_label      VARCHAR(16)  NOT NULL,
    report_count        INTEGER      NOT NULL DEFAULT 0,
    first_reported_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    last_reported_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    status_updated_at   TIMESTAMP WITH TIME ZONE,
    status_updated_by   VARCHAR(64),
    confirmed_at        TIMESTAMP WITH TIME ZONE,
    confirmed_by        VARCHAR(64),
    closed_at           TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    version             BIGINT       NOT NULL DEFAULT 0
);

CREATE INDEX idx_incident_status_priority
    ON incident (status, priority_score DESC, first_reported_at ASC);
CREATE INDEX idx_incident_sector_window
    ON incident (sector_key, status, last_reported_at DESC);

CREATE TABLE report (
    id                  UUID PRIMARY KEY,
    client_id           VARCHAR(64),
    sector              VARCHAR(120),
    sector_key          VARCHAR(120),
    reference           VARCHAR(200),
    failure_type        VARCHAR(40)  NOT NULL,
    description         VARCHAR(1000) NOT NULL,
    latitude            NUMERIC(10, 7),
    longitude           NUMERIC(10, 7),
    reported_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    incident_id         UUID REFERENCES incident (id),
    link_status         VARCHAR(24)  NOT NULL,
    link_certainty      VARCHAR(16),
    grouping_reason     VARCHAR(1000),
    similarity_score    NUMERIC(4, 3),
    link_updated_at     TIMESTAMP WITH TIME ZONE,
    link_updated_by     VARCHAR(64),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_report_incident ON report (incident_id);
CREATE INDEX idx_report_reported_at ON report (reported_at DESC);
CREATE INDEX idx_report_status ON report (link_status);

CREATE TABLE report_link_history (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id           UUID NOT NULL REFERENCES report (id),
    from_incident_id    UUID REFERENCES incident (id),
    to_incident_id      UUID REFERENCES incident (id),
    action              VARCHAR(24) NOT NULL,
    actor_id            VARCHAR(64),
    note                VARCHAR(500),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_link_history_report ON report_link_history (report_id, created_at DESC);

COMMENT ON TABLE incident IS 'Incidencia padre (relacion 1:N con report)';
COMMENT ON TABLE report IS 'Reporte original del cliente; nunca se elimina ni se altera su contenido';
COMMENT ON TABLE report_link_history IS 'Trazabilidad de vinculacion, separacion y reasignacion de reportes';

-- =====================================================================
-- V4 - Auditoria transversal e historial de estados de la incidencia
--
-- report_link_history (V1) registra los vinculos de cada reporte.
-- incident_status_history registra el ciclo de vida del caso: quien lo
-- confirmo, quien lo asigno, quien inicio la atencion y con que nota se
-- resolvio. audit_event registra accesos y acciones sensibles.
-- =====================================================================

CREATE TABLE incident_status_history (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id         UUID NOT NULL REFERENCES incident (id),
    event_type          VARCHAR(24) NOT NULL,
    from_status         VARCHAR(24),
    to_status           VARCHAR(24) NOT NULL,
    actor_id            VARCHAR(64),
    actor_role          VARCHAR(16),
    note                VARCHAR(500),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_status_history_incident ON incident_status_history (incident_id, created_at);

CREATE TABLE audit_event (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id            VARCHAR(64),
    actor_role          VARCHAR(16),
    action              VARCHAR(40) NOT NULL,
    entity_type         VARCHAR(40),
    entity_id           VARCHAR(64),
    detail              VARCHAR(500),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_audit_event_created ON audit_event (created_at DESC);
CREATE INDEX idx_audit_event_actor ON audit_event (actor_id, created_at DESC);

COMMENT ON TABLE incident_status_history IS 'Cambios de estado y asignaciones del caso, con actor y nota';
COMMENT ON TABLE audit_event IS 'Auditoria de accesos y acciones sensibles (sin contrasenas ni descripciones)';

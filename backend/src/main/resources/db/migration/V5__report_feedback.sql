-- =====================================================================
-- V5 - Calificacion de la atencion por parte del cliente
--
-- Una calificacion por reporte, solo cuando el caso esta RESUELTA o CERRADA.
-- Si la falla persiste, el cliente usa /persistence (C7), no la calificacion.
-- =====================================================================

CREATE TABLE report_feedback (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id           UUID NOT NULL REFERENCES report (id),
    rating              SMALLINT NOT NULL,
    comment             VARCHAR(500),
    actor_id            VARCHAR(64),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_report_feedback_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE UNIQUE INDEX ux_report_feedback_report ON report_feedback (report_id);
CREATE INDEX idx_report_client ON report (client_id, reported_at DESC);
